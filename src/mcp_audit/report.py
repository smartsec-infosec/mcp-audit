"""Output renderers: console, JSON, SARIF 2.1.0, Markdown."""
from __future__ import annotations
import datetime, json
from . import __version__
from .checks import CHECKS, SEVERITIES, sev_rank

DISCLAIMER = ("All checks are heuristic (pattern-based static analysis of MCP metadata). Findings require manual "
              "validation by a qualified tester; absence of findings does not prove a server is safe.")


def sort(findings):
    return sorted(findings, key=lambda f: (-sev_rank(f.severity), f.check_id, f.target))


def counts(findings):
    return {s: sum(f.severity == s for f in findings) for s in reversed(SEVERITIES)}


def to_json(findings, inventory):
    return json.dumps({"tool": "mcp-audit", "version": __version__, "vendor": "SmartSec (https://smartsec.co.uk)",
                       "generated": datetime.datetime.now(datetime.timezone.utc).isoformat(),
                       "summary": counts(findings), "inventory": inventory,
                       "findings": [f.to_dict() for f in sort(findings)]}, indent=2, ensure_ascii=False)


def to_sarif(findings):
    lvl = {"critical": "error", "high": "error", "medium": "warning", "low": "note", "info": "note"}
    rules = [{"id": cid, "name": c[0], "shortDescription": {"text": c[0]}, "fullDescription": {"text": c[2]},
              "help": {"text": c[3]}, "properties": {"tags": c[4] + c[5], "security-severity":
                                                     {"critical": "9.5", "high": "8.0", "medium": "5.5", "low": "3.0", "info": "1.0"}[c[1]]}}
             for cid, c in CHECKS.items()]
    results = [{"ruleId": f.check_id, "level": lvl[f.severity],
                "message": {"text": f"{f.title} in {f.target}: {f.evidence}"},
                "locations": [{"logicalLocations": [{"fullyQualifiedName": f.target, "kind": "function"}]}],
                "properties": {"severity": f.severity}} for f in sort(findings)]
    return json.dumps({"$schema": "https://json.schemastore.org/sarif-2.1.0.json", "version": "2.1.0",
                       "runs": [{"tool": {"driver": {"name": "mcp-audit", "version": __version__,
                                                     "informationUri": "https://smartsec.co.uk", "rules": rules}},
                                 "results": results}]}, indent=2, ensure_ascii=False)


def _md(s):
    return str(s).replace("|", "\\|").replace("\n", " ").replace("<", "&lt;")


def _vis(s):
    """Make hidden characters visible in reports."""
    return "".join(c if c.isprintable() else f"<U+{ord(c):04X}>" for c in s)


def to_markdown(findings, inventory, title="MCP Server Security Assessment"):
    now = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    c = counts(findings)
    L = [f"# {title}", "", f"*Generated by mcp-audit v{__version__} by [SmartSec](https://smartsec.co.uk) on {now}*", "",
         "## Summary", "", "| Severity | Count |", "|---|---|"] + [f"| {s.title()} | {n} |" for s, n in c.items()] + [""]
    L += ["## Scope / inventory", "", "| Server | Version | Tools | Resources | Prompts |", "|---|---|---|---|---|"]
    for s, d in inventory.items():
        si = d.get("serverInfo") or {}
        L.append(f"| {_md(s)} | {_md(si.get('name', ''))} {_md(si.get('version', ''))} | {d.get('tools', 0)} | {d.get('resources', 0)} | {d.get('prompts', 0)} |")
    L += ["", "## Findings overview", "", "| # | ID | Severity | Target | Title |", "|---|---|---|---|---|"]
    fs = sort(findings)
    for i, f in enumerate(fs, 1):
        L.append(f"| {i} | {f.check_id} | {f.severity.upper()} | `{_md(f.target)}` | {_md(f.title)} |")
    L += ["", "## Finding details", ""]
    for i, f in enumerate(fs, 1):
        L += [f"### {i}. [{f.severity.upper()}] {f.title}", "", f"- **Check:** {f.check_id} (heuristic)",
              f"- **Affected:** `{_md(f.target)}`"]
        if f.owasp:
            L.append(f"- **OWASP LLM Top 10 (2025):** {', '.join(f.owasp)}")
        if f.atlas:
            L.append(f"- **MITRE ATLAS:** {', '.join(f.atlas)}")
        L += ["", f"**Description.** {f.description}", "", "**Evidence.**", "", "```", _vis(f.evidence), "```", "",
              f"**Remediation.** {f.remediation}", ""]
    L += ["## Methodology note", "", DISCLAIMER + " mcp-audit enumerates servers via `initialize`, `tools/list`, "
          "`resources/list` and `prompts/list` only; it never invokes tools.", ""]
    return "\n".join(L)


def console(findings, inventory, file=None):
    try:
        from rich.console import Console
        from rich.table import Table
    except ImportError:
        for f in sort(findings):
            print(f"[{f.severity.upper():8}] {f.check_id} {f.target}: {f.title} - {f.evidence}", file=file)
        print(counts(findings), file=file)
        return
    con = Console(file=file, stderr=file is None)
    colours = {"critical": "bold white on red", "high": "bold red", "medium": "yellow", "low": "cyan", "info": "dim"}
    inv = Table(title="Servers", show_lines=False)
    for col in ("Server", "Tools", "Resources", "Prompts"):
        inv.add_column(col)
    for s, d in inventory.items():
        inv.add_row(s, str(d.get("tools", 0)), str(d.get("resources", 0)), str(d.get("prompts", 0)))
    con.print(inv)
    t = Table(title="mcp-audit findings (heuristic) - SmartSec", show_lines=False)
    for col in ("Sev", "ID", "Target", "Finding", "Evidence"):
        t.add_column(col, overflow="fold")
    for f in sort(findings):
        t.add_row(f"[{colours[f.severity]}]{f.severity.upper()}[/]", f.check_id, f.target, f.title,
                  _vis(f.evidence)[:120])
    con.print(t)
    con.print("  ".join(f"[{colours[s]}]{s.upper()}: {n}[/]" for s, n in counts(findings).items()))
