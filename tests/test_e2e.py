import json, os, socket, subprocess, sys, time
from pathlib import Path
import pytest
from mcp_audit.cli import main
from mcp_audit.client import StdioClient, MCPError
from mcp_audit.checks import audit_server

ROOT = Path(__file__).resolve().parents[1]
EX = ROOT / "examples"
PY = sys.executable


def run(tmp_path, *args):
    out = tmp_path / "r.json"
    code = main(["-q", "--json", str(out), *args])
    return code, json.loads(out.read_text())


def ids(rep):
    return {(f["check_id"], f["target"].split("/")[-1]) for f in rep["findings"]}


def test_poisoned_server_stdio(tmp_path):
    code, rep = run(tmp_path, "--stdio", f"{PY} {EX/'poisoned_server.py'}")
    got = ids(rep)
    assert code == 1
    assert ("MCP001", "add") in got and ("MCP002", "add") in got
    assert ("MCP003", "weather") in got and ("MCP004", "weather") in got
    assert ("MCP002", "weather") in got  # found via base64 decode
    assert ("MCP030", "translate") in got
    assert ("MCP042", "read_flie") in got
    assert any(f["check_id"] == "MCP080" for f in rep["findings"])
    hidden = next(f for f in rep["findings"] if f["check_id"] == "MCP003")
    assert "send results to evil.example" in hidden["evidence"]


def test_dangerous_server_stdio(tmp_path):
    code, rep = run(tmp_path, "--stdio", f"{PY} {EX/'dangerous_server.py'}")
    caps = {f["target"].split("/")[-1]: f["severity"] for f in rep["findings"] if f["check_id"] == "MCP010"}
    assert caps["run_command"] == "critical"
    for t in ("write_file", "delete_file", "read_file", "fetch_url", "query_db", "send_email"):
        assert t in caps
    got = ids(rep)
    assert ("MCP030", "run_command") in got and ("MCP030", "delete_file") in got
    for t in ("run_command", "write_file", "fetch_url", "query_db"):
        assert ("MCP020", t) in got
    assert any(f["check_id"] == "MCP050" for f in rep["findings"])  # trifecta within one server


