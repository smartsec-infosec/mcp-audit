def test_collision(tmp_path):
    a = tmp_path / "a.json"; b = tmp_path / "b.json"
    a.write_text(json.dumps({"serverInfo": {"name": "a"}, "tools": [{"name": "search", "description": "x"}]}))
    b.write_text(json.dumps({"serverInfo": {"name": "b"}, "tools": [{"name": "search", "description": "y"}]}))
    _, rep = run(tmp_path, "--dump", str(a), "--dump", str(b))
    assert any(f["check_id"] == "MCP040" for f in rep["findings"])


