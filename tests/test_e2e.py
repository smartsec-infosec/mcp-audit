def _free_port():
    s = socket.socket(); s.bind(("127.0.0.1", 0)); p = s.getsockname()[1]; s.close(); return p


@pytest.mark.parametrize("sse", [False, True])
def test_http_transport(tmp_path, sse):
    port = _free_port()
    args = [PY, str(EX / "http_server.py"), str(port), "--token", "t0k"] + (["--sse"] if sse else [])
    p = subprocess.Popen(args)
    try:
        for _ in range(50):
            try:
                socket.create_connection(("127.0.0.1", port), 0.1).close(); break
            except OSError:
                time.sleep(0.1)
        code, rep = run(tmp_path, "--url", f"http://127.0.0.1:{port}/mcp", "--header", "Authorization: Bearer t0k")
        assert ("MCP010", "fetch_url") in ids(rep)
        code, rep = run(tmp_path, "--url", f"http://127.0.0.1:{port}/mcp")  # no auth -> 401 -> enumeration fails
        assert rep["inventory"] == {} and code == 3
    finally:
        p.terminate()


